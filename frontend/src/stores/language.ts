// ===== i18n 字典（自动生成区域结束）=====

export const useLanguageStore = defineStore('language', () => {
  const locale = ref(readSavedLocale())

  function setLocale(code: string) {
    if (!languages.some((item) => item.code === code)) {
      return
    }
    locale.value = code
    try {
      localStorage.setItem(STORAGE_KEY, code)
    } catch {
      // 忽略持久化失败
    }
  }

  // toOr('字典key', '默认中文文本')：当前语言有翻译则返回翻译，否则回退默认文本。
  function toOr(key: string, text: string): string {
    if (locale.value === DEFAULT_LOCALE) {
      return text
    }
    return dict[locale.value]?.[key] ?? text
  }

  return {
    locale,
    languages,
    setLocale,
    toOr,
  }
})
